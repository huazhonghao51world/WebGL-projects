/** 相对坐标 rel（0–1，按包围盒）在 t 秒时的温度。size 为包围盒尺寸（m），半径按米计算。 */
export function temperatureAt(def, rel, size, t) {
  // 各热源取最大温升（相邻加热段不叠加），符合“表面温度不高于最热热源”的物理直觉。
  return def.base + def.sources.reduce((top, [p, amp, radius, wave]) => {
    const d = Math.hypot((rel[0] - p[0]) * size[0], (rel[1] - p[1]) * size[1], (rel[2] - p[2]) * size[2]);
    return Math.max(top, amp * wave(t) * Math.exp(-(d * d) / (2 * radius * radius)));
  }, 0);
}

// turbo 色带（Google Turbo 多项式近似），用于热成像着色与图例。
export function turbo(x) {
  const v = Math.min(1, Math.max(0, x));
  const r = 0.13572138 + v * (4.6153926 + v * (-42.66032258 + v * (132.13108234 + v * (-152.94239396 + v * 59.28637943))));
  const g = 0.09140261 + v * (2.19418839 + v * (4.84296658 + v * (-14.18503333 + v * (4.27729857 + v * 2.82956604))));
  const b = 0.1066733 + v * (12.64194608 + v * (-60.58204836 + v * (110.36276771 + v * (-89.90310912 + v * 27.34824973))));
  return [r, g, b].map((c) => Math.min(1, Math.max(0, c)));
}
